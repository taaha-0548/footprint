"""Write ENVIRONMENT.md (PRD Section 4, step 7). Reads local machine facts only."""
from __future__ import annotations

import hashlib
import os
import platform
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def sh(*cmd: str) -> str:
    return subprocess.run(cmd, capture_output=True, text=True, check=False).stdout.strip()


def mem_gb() -> str:
    for line in Path("/proc/meminfo").read_text().splitlines():
        if line.startswith("MemTotal"):
            return f"{int(line.split()[1]) / 1048576:.1f} GB"
    return "unknown"


def main() -> None:
    lock = ROOT / "uv.lock"
    lock_hash = hashlib.sha256(lock.read_bytes()).hexdigest() if lock.exists() else "missing"
    free = shutil.disk_usage(ROOT).free / 1e9
    rows = [
        ("OS", platform.platform()),
        ("CPU", f"{platform.processor() or platform.machine()} x{os.cpu_count()}"),
        ("RAM (total)", mem_gb()),
        ("Free disk", f"{free:.0f} GB"),
        ("git", sh("git", "--version")),
        ("Python", sys.version.split()[0]),
        ("uv", sh("uv", "--version")),
        ("uv.lock sha256", lock_hash),
    ]
    body = "# ENVIRONMENT\n\nGenerated by `make env`. Do not edit by hand.\n\n| Item | Value |\n| --- | --- |\n"
    body += "".join(f"| {k} | {v} |\n" for k, v in rows)
    body += "\nNotes: `git merge-tree --write-tree` needs git >= 2.38 (checked in M0).\n"
    (ROOT / "ENVIRONMENT.md").write_text(body)


if __name__ == "__main__":
    main()
